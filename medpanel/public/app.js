import { vault, slimReport } from "./vault.js";

const $ = (s) => document.querySelector(s);
const FLAG_TEXT = {
  critical_low: "Critical low", critical_high: "Critical high", implausible: "Verify",
  low: "Low", high: "High", normal: "Normal", unknown: "—",
};

// All state lives in memory unless the user unlocks the encrypted vault.
const state = { current: null, session: [], saved: [], passphrase: null, chart: null };

// Model output is untrusted text: build DOM with textContent only.
function el(tag, attrs = {}, ...children) {
  const n = document.createElement(tag);
  for (const [k, v] of Object.entries(attrs)) k === "class" ? (n.className = v) : n.setAttribute(k, v);
  for (const c of children.flat()) if (c != null) n.append(c instanceof Node ? c : String(c));
  return n;
}
const list = (items) => el("ul", {}, (items ?? []).map((i) => el("li", {}, i)));

// ---------- consent ----------
const consent = $("#consent");
function hasConsent() {
  try { return sessionStorage.getItem("medpanel.consent") === "1"; } catch { return false; }
}
if (!hasConsent()) consent.showModal();
consent.addEventListener("cancel", (e) => e.preventDefault());
$("#consent-form").addEventListener("submit", () => {
  try { sessionStorage.setItem("medpanel.consent", "1"); } catch {}
});

fetch("/api/config").then((r) => r.json()).then((c) => {
  $("#mode").textContent = c.offline ? "Offline mode: built-in rules only" : "No data retained on the server";
});

// ---------- upload ----------
$("#upload-form").addEventListener("submit", async (e) => {
  e.preventDefault();
  if (!hasConsent()) return consent.showModal();
  const file = $("#file").files[0];
  if (!file) return;
  const fd = new FormData();
  fd.append("consent", "accepted");
  fd.append("report", file);
  const btn = $("#analyse-btn");
  btn.disabled = true;
  $("#status").textContent = "Reading report and consulting the specialist panel… this can take a minute.";
  try {
    const res = await fetch("/api/analyze", { method: "POST", body: fd });
    const body = await res.json();
    if (!res.ok) throw new Error(body.error || "Analysis failed");
    state.current = body;
    state.session.push(slimReport(body));
    renderReport(body);
    renderTrends();
    $("#status").textContent = "";
    $("#file").value = "";
  } catch (err) {
    $("#status").textContent = err.message;
  } finally {
    btn.disabled = false;
  }
});

// ---------- report ----------
function renderReport(r) {
  const s = r.synthesis;
  $("#report").hidden = false;

  const banner = $("#critical-banner");
  banner.replaceChildren();
  const alerts = s.critical_alerts?.length ? s.critical_alerts : r.criticals.map((c) => c.message);
  banner.hidden = !alerts.length;
  if (alerts.length) {
    banner.append(el("h3", {}, "Critical values — contact a clinician promptly"), list(alerts),
      el("p", { class: "note" }, "These alerts are generated by fixed safety rules, independent of the AI review."));
  }
  if (r.implausible.length) {
    banner.hidden = false;
    banner.append(el("p", {}, `Please check against the original report (possible reading error): ${r.implausible.join(", ")}.`));
  }

  $("#headline").textContent = s.headline;
  const u = $("#urgency");
  u.textContent = { routine: "Routine", soon: "See doctor soon", urgent: "Urgent" }[s.urgency] ?? s.urgency;
  u.className = `pill ${s.urgency}`;
  $("#summary").textContent = s.overall_summary;

  const tbody = $("#results tbody");
  tbody.replaceChildren(...r.analytes.map((a) => {
    const ref = a.ref_low != null || a.ref_high != null ? `${a.ref_low ?? ""} – ${a.ref_high ?? ""}` : "";
    return el("tr", { class: a.flag },
      el("td", {}, a.label, a.reason ? el("div", { class: "note" }, a.reason) : null),
      el("td", {}, a.value_text), el("td", {}, a.unit), el("td", {}, ref),
      el("td", {}, el("span", { class: `flag ${a.flag}` }, FLAG_TEXT[a.flag])));
  }));

  const syn = $("#synthesis");
  syn.replaceChildren(el("h3", {}, "Chief Physician summary"));
  for (const k of s.key_issues ?? []) {
    syn.append(el("div", { class: `sig-${k.priority}` }, el("strong", {}, k.title), el("p", {}, k.explanation),
      k.specialists?.length ? el("p", { class: "note" }, `Raised by: ${k.specialists.join(", ")}`) : null));
  }
  const section = (title, items) => items?.length && syn.append(el("h4", {}, title), list(items));
  section("Reassuring findings", s.reassuring_findings);
  section("Suggested next steps", s.next_steps);
  section("Questions for your doctor", s.questions_for_doctor);
  section("Limitations", s.limitations);

  $("#specialists").replaceChildren(...r.specialists.filter((sp) => !sp.skipped).map((sp) =>
    el("div", { class: "card" }, el("h3", {}, sp.title),
      sp.error ? el("p", { class: "muted" }, `Unavailable: ${sp.error}`) : [
        el("p", {}, sp.summary),
        (sp.findings ?? []).map((f) => el("div", { class: `sig-${f.significance}` }, el("strong", {}, f.analyte), " — ", f.interpretation)),
        sp.patterns?.length ? [el("h4", {}, "Patterns"), list(sp.patterns)] : null,
        sp.follow_up_tests?.length ? [el("h4", {}, "Tests a doctor may consider"), list(sp.follow_up_tests)] : null,
      ])));
}

// ---------- trends ----------
function allReports() {
  const byId = new Map();
  for (const r of [...state.saved, ...state.session]) byId.set(r.id, r);
  return [...byId.values()].sort((a, b) => a.date.localeCompare(b.date));
}

function trendSeries() {
  const series = new Map();
  for (const r of allReports()) {
    for (const a of r.analytes) {
      if (!series.has(a.key)) series.set(a.key, { key: a.key, label: a.label, unit: a.unit, points: [] });
      series.get(a.key).points.push({ date: r.date, value: a.value, flag: a.flag });
    }
  }
  return [...series.values()];
}

const POINT_COLOURS = { critical_low: "#b91c1c", critical_high: "#b91c1c", low: "#d97706", high: "#d97706", normal: "#16a34a", implausible: "#7e22ce", unknown: "#6b7280" };

function renderTrends() {
  const series = trendSeries().filter((s) => s.points.length >= 2);
  const sel = $("#trend-select");
  const prev = sel.value;
  sel.replaceChildren(...series.map((s) => el("option", { value: s.key }, `${s.label} (${s.points.length})`)));
  $("#trend-note").hidden = series.length > 0;
  if (!series.length) { state.chart?.destroy(); state.chart = null; return; }
  if (series.some((s) => s.key === prev)) sel.value = prev;
  drawChart(series.find((s) => s.key === sel.value));
}
$("#trend-select").addEventListener("change", renderTrends);

function drawChart(s) {
  state.chart?.destroy();
  const css = getComputedStyle(document.documentElement);
  state.chart = new Chart($("#trend-chart"), {
    type: "line",
    data: {
      labels: s.points.map((p) => p.date),
      datasets: [{
        label: `${s.label}${s.unit ? ` (${s.unit})` : ""}`,
        data: s.points.map((p) => p.value),
        borderColor: css.getPropertyValue("--accent").trim(),
        pointBackgroundColor: s.points.map((p) => POINT_COLOURS[p.flag]),
        pointRadius: 6, tension: 0.2,
      }],
    },
    options: {
      animation: false,
      plugins: { legend: { labels: { color: css.getPropertyValue("--text").trim() } } },
      scales: {
        x: { ticks: { color: css.getPropertyValue("--muted").trim() } },
        y: { ticks: { color: css.getPropertyValue("--muted").trim() } },
      },
    },
  });
}

// ---------- PDF export ----------
$("#pdf-btn").addEventListener("click", async () => {
  if (!state.current) return;
  const res = await fetch("/api/export-pdf", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      report: state.current,
      chartPng: state.chart ? $("#trend-chart").toDataURL("image/png") : null,
      trends: trendSeries().filter((s) => s.points.length >= 2),
    }),
  });
  if (!res.ok) return alert("PDF export failed");
  const url = URL.createObjectURL(await res.blob());
  el("a", { href: url, download: `medpanel-${state.current.report_date ?? "report"}.pdf` }).click();
  setTimeout(() => URL.revokeObjectURL(url), 5000);
});

// ---------- encrypted vault ----------
const vstatus = (t) => ($("#vault-status").textContent = t);

$("#vault-form").addEventListener("submit", async (e) => {
  e.preventDefault();
  const pass = $("#passphrase").value;
  try {
    state.saved = await vault.load(pass);
    state.passphrase = pass;
    $("#passphrase").value = "";
    vstatus(vault.exists() ? `Unlocked: ${state.saved.length} saved report(s).` : "New history ready. Use “Save to encrypted history” to add reports.");
    renderTrends();
  } catch (err) {
    vstatus(err.message);
  }
});

$("#save-btn").addEventListener("click", async () => {
  if (!state.current) return;
  if (!state.passphrase) {
    $("#passphrase").focus();
    return vstatus("Enter a passphrase and press Unlock first. Nothing is saved until you do.");
  }
  const slim = slimReport(state.current);
  state.saved = [...state.saved.filter((r) => r.id !== slim.id), slim];
  await vault.save(state.saved, state.passphrase);
  vstatus(`Saved. ${state.saved.length} report(s) in encrypted history.`);
});

$("#vault-export").addEventListener("click", () => {
  const blob = vault.exportBlob();
  if (!blob) return vstatus("No saved history to back up.");
  const url = URL.createObjectURL(new Blob([blob], { type: "application/json" }));
  el("a", { href: url, download: "medpanel-history.encrypted.json" }).click();
  setTimeout(() => URL.revokeObjectURL(url), 5000);
});

$("#vault-import").addEventListener("change", async (e) => {
  const f = e.target.files[0];
  if (!f) return;
  try {
    vault.importBlob(await f.text());
    state.saved = [];
    state.passphrase = null;
    vstatus("Backup restored. Enter its passphrase and press Unlock.");
  } catch (err) {
    vstatus(err.message);
  }
  e.target.value = "";
});

$("#vault-wipe").addEventListener("click", () => {
  if (!confirm("Delete all saved history on this device? This cannot be undone.")) return;
  vault.wipe();
  Object.assign(state, { saved: [], session: [], passphrase: null });
  renderTrends();
  vstatus("All history deleted.");
});
