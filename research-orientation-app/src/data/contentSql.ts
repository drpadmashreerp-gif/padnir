// Builds the SQL that stores the whole book as one protected database row (used by npm run export:content).
import * as BOOK from './content/index';

export function contentSql() {
  const payload = JSON.stringify({ version: 1, ...BOOK });
  if (payload.includes('$book$')) throw new Error('Content contains the SQL quote marker');
  return `-- Research Methodology Orientation: book content (generated by npm run export:content; do not edit by hand).
-- Run in Supabase → SQL Editor AFTER schema.sql. Run it again whenever the chapters are updated.
insert into public.book_content (id, data, updated_at)
values ('book', $book$${payload}$book$::jsonb, now())
on conflict (id) do update set data = excluded.data, updated_at = now();
`;
}
